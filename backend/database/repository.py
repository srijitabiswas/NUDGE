"""Data access repository for NUDGE tasks.

Provides parameterized functions to insert, retrieve, and update tasks according
to the 19-field Step 3 Shared Structured JSON / Data Contract (PROJECT.md).
"""

from __future__ import annotations

from datetime import datetime
import json
import sqlite3
from typing import Any, Dict, List, Optional

from backend.database.connection import get_connection

# Exact 19-field sequence defined in PROJECT.md Step 3 Data Contract
CONTRACT_FIELD_ORDER = [
    "task_id",
    "task_title",
    "description",
    "task_type",
    "subject",
    "due_date",
    "due_time",
    "due_datetime",
    "event_datetime",
    "status",
    "importance",
    "estimated_effort",
    "source",
    "raw_text",
    "date_time_expression",
    "confidence",
    "change_information",
    "created_at",
    "completed_at",
]

VALID_STATUSES = ("pending", "in_progress", "completed", "cancelled")


def normalize_due_datetime(
    due_date: Optional[str],
    due_time: Optional[str],
    explicit_due_datetime: Optional[str] = None,
) -> Optional[str]:
    """Derive due_datetime strictly when both due_date and due_time are present.

    Rules:
    - If explicit_due_datetime is provided, preserve it.
    - If both due_date ('YYYY-MM-DD') and due_time ('HH:MM' or 'HH:MM:SS') are
      available, combine them into ISO 8601 extended format ('YYYY-MM-DDTHH:MM:SS').
    - If due_time is missing/null, due_datetime MUST remain None (NULL).
    - Under no circumstances is 23:59 or any fallback time invented.
    """
    if explicit_due_datetime:
        return explicit_due_datetime

    if not due_date or not due_time:
        return None

    cleaned_date = str(due_date).strip()
    cleaned_time = str(due_time).strip()

    if not cleaned_date or not cleaned_time:
        return None

    time_parts = cleaned_time.split(":")
    if len(time_parts) == 2:
        return f"{cleaned_date}T{cleaned_time}:00"
    elif len(time_parts) == 3:
        return f"{cleaned_date}T{cleaned_time}"

    return None


def serialize_change_information(change_info: Any) -> str:
    """Serialize change_information to a valid JSON array text for storage."""
    if change_info is None:
        return "[]"
    if isinstance(change_info, (list, tuple)):
        return json.dumps(list(change_info), ensure_ascii=False)
    if isinstance(change_info, str):
        # Validate that string is valid JSON array; otherwise SQLite check constraint will trigger
        return change_info
    return "[]"


def _row_to_contract_dict(row: sqlite3.Row) -> Dict[str, Any]:
    """Convert a database row into a dictionary matching the 19-field contract format."""
    # Decode change_information back to Python list
    raw_change_info = row["change_information"]
    decoded_change_info: List[Dict[str, Any]] = []
    if raw_change_info:
        try:
            parsed = json.loads(raw_change_info)
            if isinstance(parsed, list):
                decoded_change_info = parsed
        except (json.JSONDecodeError, TypeError):
            decoded_change_info = []

    return {
        "task_id": row["task_id"],
        "task_title": row["task_title"],
        "description": row["description"],
        "task_type": row["task_type"],
        "subject": row["subject"],
        "due_date": row["due_date"],
        "due_time": row["due_time"],
        "due_datetime": row["due_datetime"],
        "event_datetime": row["event_datetime"],
        "status": row["status"],
        "importance": row["importance"],
        "estimated_effort": row["estimated_effort"],
        "source": row["source"],
        "raw_text": row["raw_text"],
        "date_time_expression": row["date_time_expression"],
        "confidence": row["confidence"],
        "change_information": decoded_change_info,
        "created_at": row["created_at"],
        "completed_at": row["completed_at"],
    }


def insert_task(
    task_data: Dict[str, Any],
    db_path: Optional[str] = None,
    connection: Optional[sqlite3.Connection] = None,
) -> int:
    """Insert a structured task record into the tasks table.

    Requirements enforced:
    - task_id is generated by SQLite (autoincrement primary key).
    - created_at is generated by SQLite column default unless explicitly provided.
    - due_datetime is normalized strictly when both due_date and due_time exist.
    - change_information is stored as valid JSON array text.
    - Missing/unknown optional fields are preserved as NULL.
    - Uses fully parameterized SQL queries.

    Returns the generated task_id.
    """
    # Validate required task content (task_title; task_type may be null)
    task_title = task_data.get("task_title")
    if task_title is None or not isinstance(task_title, str) or not task_title.strip():
        raise ValueError(
            "Cannot insert task: 'task_title' is missing, non-string, or empty. "
            "General notices and non-actionable messages must be filtered before database insertion."
        )

    task_type = task_data.get("task_type")
    if task_type is not None and not isinstance(task_type, str):
        raise ValueError("Cannot insert task: 'task_type' must be a string or null.")
    if isinstance(task_type, str) and not task_type.strip():
        task_type = None  # a blank task_type is stored as NULL

    due_date = task_data.get("due_date")
    due_time = task_data.get("due_time")
    normalized_due = normalize_due_datetime(
        due_date,
        due_time,
        task_data.get("due_datetime"),
    )

    change_info_text = serialize_change_information(
        task_data.get("change_information")
    )

    status = task_data.get("status") or "pending"
    confidence = (
        task_data.get("confidence")
        if task_data.get("confidence") is not None
        else 0.0
    )

    completed_at = task_data.get("completed_at")
    if status == "completed" and not completed_at:
        completed_at = datetime.now().strftime("%Y-%m-%dT%H:%M:%S")

    explicit_created_at = task_data.get("created_at")

    # Build parameterized query depending on whether created_at is explicit
    columns = [
        "task_title",
        "description",
        "task_type",
        "subject",
        "due_date",
        "due_time",
        "due_datetime",
        "event_datetime",
        "date_time_expression",
        "status",
        "importance",
        "estimated_effort",
        "source",
        "raw_text",
        "confidence",
        "change_information",
        "completed_at",
    ]
    values = [
        task_data.get("task_title"),
        task_data.get("description"),
        task_type,
        task_data.get("subject"),
        due_date,
        due_time,
        normalized_due,
        task_data.get("event_datetime"),
        task_data.get("date_time_expression"),
        status,
        task_data.get("importance"),
        task_data.get("estimated_effort"),
        task_data.get("source"),
        task_data.get("raw_text"),
        confidence,
        change_info_text,
        completed_at,
    ]

    if explicit_created_at is not None:
        columns.append("created_at")
        values.append(explicit_created_at)

    placeholders = ", ".join("?" for _ in columns)
    sql = f"INSERT INTO tasks ({', '.join(columns)}) VALUES ({placeholders})"

    owns_connection = connection is None
    con = connection or get_connection(db_path)
    try:
        cursor = con.cursor()
        cursor.execute(sql, values)
        task_id = cursor.lastrowid
        con.commit()
        return task_id
    finally:
        if owns_connection:
            con.close()


def get_task_by_id(
    task_id: int,
    db_path: Optional[str] = None,
    connection: Optional[sqlite3.Connection] = None,
) -> Optional[Dict[str, Any]]:
    """Retrieve a task record by its task_id.

    Returns the record shaped to the 19-field contract with decoded
    change_information, or None if no record matches task_id.
    """
    owns_connection = connection is None
    con = connection or get_connection(db_path)
    try:
        cursor = con.cursor()
        cursor.execute("SELECT * FROM tasks WHERE task_id = ?", (task_id,))
        row = cursor.fetchone()
        if not row:
            return None
        return _row_to_contract_dict(row)
    finally:
        if owns_connection:
            con.close()


def update_task_status(
    task_id: int,
    new_status: str,
    db_path: Optional[str] = None,
    connection: Optional[sqlite3.Connection] = None,
) -> bool:
    """Update task status with authoritative storage lifecycle handling.

    - Transitions to 'completed' record completed_at timestamp.
    - Transitions to 'pending' or 'in_progress' clear completed_at (NULL).
    - Transitions to 'cancelled' preserve completed_at state unless specified.

    Returns True if a task was found and updated, False otherwise.
    """
    if new_status not in VALID_STATUSES:
        raise ValueError(
            f"Invalid status '{new_status}'. Allowed values: {VALID_STATUSES}"
        )

    owns_connection = connection is None
    con = connection or get_connection(db_path)
    try:
        cursor = con.cursor()
        if new_status == "completed":
            completed_at = datetime.now().strftime("%Y-%m-%dT%H:%M:%S")
            cursor.execute(
                "UPDATE tasks SET status = ?, completed_at = ? WHERE task_id = ?",
                (new_status, completed_at, task_id),
            )
        elif new_status in ("pending", "in_progress"):
            cursor.execute(
                "UPDATE tasks SET status = ?, completed_at = NULL WHERE task_id = ?",
                (new_status, task_id),
            )
        else:  # cancelled
            cursor.execute(
                "UPDATE tasks SET status = ? WHERE task_id = ?",
                (new_status, task_id),
            )

        con.commit()
        return cursor.rowcount > 0
    finally:
        if owns_connection:
            con.close()


def get_all_tasks(
    db_path: Optional[str] = None,
    connection: Optional[sqlite3.Connection] = None,
) -> List[Dict[str, Any]]:
    """Retrieve all tasks ordered by task_id in contract format."""
    owns_connection = connection is None
    con = connection or get_connection(db_path)
    try:
        cursor = con.cursor()
        cursor.execute("SELECT * FROM tasks ORDER BY task_id ASC")
        rows = cursor.fetchall()
        return [_row_to_contract_dict(row) for row in rows]
    finally:
        if owns_connection:
            con.close()
